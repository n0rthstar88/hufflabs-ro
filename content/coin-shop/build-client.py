def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
out = ['-- HuffLabs RO custom items. Generated by content/coin-shop/build-client.py, don\'t edit by hand.',
       '-- Table for Custom Items', 'tbl_custom = {']
for iid, base, name, slots, desc in items:
    ures, ires, cls = res(base)
    out += ['\t[%d] = {' % iid,
            '\t\tunidentifiedDisplayName = %s,' % q(name),
            '\t\tunidentifiedResourceName = %s,' % ures,
            '\t\tunidentifiedDescriptionName = { "" },',
            '\t\tidentifiedDisplayName = %s,' % q(name),
            '\t\tidentifiedResourceName = %s,' % ires,
            '\t\tidentifiedDescriptionName = {']
    out += ['\t\t\t%s%s' % (q(l), ',' if n < len(desc) - 1 else '') for n, l in enumerate(desc)]
    out += ['\t\t},', '\t\tslotCount = %d,' % slots, '\t\tClassNum = %s,' % cls, '\t\tcostume = false', '\t},']
out += ['}', '', '-- Table for Official Overrides', 'tbl_override = {', '}', '']
dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'client', 'itemInfo_C.lua')
open(dst, 'w', encoding='latin-1', newline='\r\n').write('\n'.join(out))
print('wrote', dst)
