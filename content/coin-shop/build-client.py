out += ['}', '', '-- Table for Official Overrides', 'tbl_override = {', '}', '']
dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'client', 'itemInfo_C.lua')
open(dst, 'w', encoding='latin-1', newline='\r\n').write('\n'.join(out))
print('wrote', dst)
