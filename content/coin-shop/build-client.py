#!/usr/bin/env python3
"""Writes client/itemInfo_C.lua (the client's custom item table) for the coin shop items.
Sprite and icon names are copied from official items in the client's own itemInfo.lua.
Usage: build-client.py <client>/SystemEN/LuaFiles514/itemInfo.lua"""
import re, sys, os
src = open(sys.argv[1], encoding='latin-1').read()
def res(i):
    b = re.search(r'\n\t\[%d\] = \{(.*?)\n\t\},' % i, src, re.S).group(1)
    g = lambda k: re.search(r'\n\t\t%s = ([^\n]*),' % k, b).group(1)
    return g('unidentifiedResourceName'), g('identifiedResourceName'), g('ClassNum')
B = '^000088'; E = '^000000'
