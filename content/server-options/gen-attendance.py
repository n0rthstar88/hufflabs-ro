#!/usr/bin/env python3
"""Writes server/attendance.yml: the client's attendance calendar (20 days per month).
Each calendar month is its own period (the client's counter starts over each month), and the
reward grows by one HuffLabs Coin per day you check in: day 1 = 1 coin ... day 20 = 20 coins.
The login-streak milestones (30/90/180/365 days in a row) live in server/npc/daily_streak.txt.

usage: gen-attendance.py [first year] [last year]   (default 2026 2035)
"""
import calendar
import pathlib
import sys

COIN = 2600000  # HuffLabs Coin
first, last = (int(a) for a in sys.argv[1:3]) if len(sys.argv) > 2 else (2026, 2035)
out = ["# Generated by gen-attendance.py: edit that, not this file. Installed as db/import/attendance.yml.",
       "Header:", "  Type: ATTENDANCE_DB", "  Version: 1", "", "Body:"]
for y in range(first, last + 1):
    for m in range(1, 13):
        if (y, m) < (2026, 11):
            continue
        out += [f"  - Start: {y}{m:02d}01", f"    End: {y}{m:02d}{calendar.monthrange(y, m)[1]:02d}", "    Rewards:"]
        for d in range(1, 21):
            out += [f"      - Day: {d}", f"        ItemId: {COIN}", f"        Amount: {d}"]
p = pathlib.Path(__file__).resolve().parent / "server" / "attendance.yml"
p.write_text("\n".join(out) + "\n")
print(f"{p}: {sum(1 for l in out if l.startswith('  - Start'))} monthly periods")
