#!/bin/bash
# HuffLabs RO seasonal events: loads the official events whose dates include today.
# Writes npc/custom/hufflabs/events.conf (imported by npc/scripts_custom.conf) and restarts the
# map server when the list changes. While anyone is online it waits (exit 75); the hourly timer retries.
#   hlro-events.sh            normal run
#   hlro-events.sh --list     print what would be loaded today, change nothing
set -euo pipefail
RA=/home/rathena/rathena
CAL=/etc/hufflabs-events.tsv
OUT=$RA/npc/custom/hufflabs/events.conf
today=$(date +%m%d)
want=$(awk -F'\t' -v t="$today" '!/^#/ && NF>=3 {
  if (($2 <= $3 && t >= $2 && t <= $3) || ($2 > $3 && (t >= $2 || t <= $3))) print "npc: npc/events/" $1 }' "$CAL")
new="// generated by hlro-events.sh on $(date +%F); edit $CAL instead
$want"
if [ "${1:-}" = --list ]; then echo "${want:-(no events today)}"; exit 0; fi
if [ -f "$OUT" ] && [ "$(grep '^npc:' "$OUT" || true)" = "$want" ]; then echo "events unchanged: ${want:-none}"; exit 0; fi
online=$(mysql -N ragnarok -e 'select count(*) from `char` where online=1')
if [ "$online" != 0 ]; then echo "events change waiting: $online online"; exit 75; fi
printf '%s\n' "$new" > "$OUT"; chown rathena:rathena "$OUT"
systemctl restart rathena-map
echo "events now: ${want:-none} (map server restarted)"
