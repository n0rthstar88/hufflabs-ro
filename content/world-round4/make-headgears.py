#!/usr/bin/env python3
"""Builds headgears.tsv from Mihael's custom item pack: every headgear with male + female
sprites and an icon becomes a stat-less costume with our own item and look ids.
usage: make-headgears.py <custom-downloads dir> > headgears.tsv
(needs mihael_x/ and extra_x/ unpacked there; extra_x holds the Valentine Ring and Flames recolours)"""
import os, re, sys
dl = sys.argv[1]
src = f"{dl}/mihael_x/Pack Custom Itens Mihael"
ACC, M, W = "¾Ç¼¼»ç¸®", "³²", "¿©"
males = {x.lower() for x in os.listdir(f"{src}/sprite/{ACC}/{M}")}
fem = {x.lower() for x in os.listdir(f"{src}/sprite/{ACC}/{W}")}
icons = {x.lower() for x in os.listdir(f"{src}/item")}
here = os.path.dirname(os.path.abspath(__file__))
english = dict(l.rstrip("\n").split("\t") for l in open(f"{here}/names_en.tsv") if l.strip() and not l.startswith("#"))
SLOT = {"256": "Top", "512": "Mid", "1": "Low", "513": "Mid,Low", "768": "Top,Mid", "769": "Top,Mid,Low", "257": "Top,Low"}
seen, names, iid, view = set(), set(), 2601000, 2936
print("# item_id\tview_id\tsprite\tslots\tname\tsource   (generated by make-headgears.py)")
for l in open(f"{src}/item_db2 (OLD).txt", encoding="latin-1").read().replace("\r\n", "\n").replace("\r", "\n").split("\n"):
    if not l or l.startswith("//"):
        continue
    f = l.split(",")
    if len(f) < 19 or f[3] != "5" or f[14] not in SLOT:
        continue
    n = f[1].lower()
    if n in seen or f"{M}_{n}.spr" not in males or f"{W}_{n}.spr" not in fem or f"{n}.bmp" not in icons:
        continue
    seen.add(n)
    name = english.get(n) or re.sub(r"\s+", " ", f[2].replace("_", " ")).strip().title() or n.replace("_", " ").title()
    name = re.sub(r"Wings's", "Wings", name)
    while name in names:
        name += " II" if not name.endswith(" II") else "I"
    names.add(name)
    print(f"{iid}\t{view}\t{n}\t{SLOT[f[14]]}\t{name}\tmihael")
    iid += 1
    view += 1

# Recolour packs: Valentine Ring (10) and Flames (19), worn as lower headgear
for pack, icondir in (("Valentine_Ring", f"texture/\u00c0\u00af\u00c0\u00fa\u00c0\u00ce\u00c5\u00cd\u00c6\u00e4\u00c0\u00cc\u00bd\u00ba/item"), ("flame_custom", "item")):
    root = f"{dl}/extra_x/{pack}"
    m = {x[len(M) + 1:-4].lower() for x in os.listdir(f"{root}/sprite/{ACC}/{M}") if x.lower().endswith(".spr")}
    w = {x[len(W) + 1:-4].lower() for x in os.listdir(f"{root}/sprite/{ACC}/{W}") if x.lower().endswith(".spr")}
    ic = {x[:-4].lower() for x in os.listdir(f"{root}/{icondir}") if x.lower().endswith(".bmp")}
    for n in sorted(m & w & ic, key=lambda k: (re.sub(r"\d+", "", k), int(re.sub(r"\D", "", k) or 0))):
        if n in seen:
            continue
        seen.add(n)
        name = re.sub(r"^Flame(\d+)$", r"Flame \1", n.replace("_", " ").title())
        while name in names:
            name += " II"
        names.add(name)
        print(f"{iid}\t{view}\t{n}\tLow\t{name}\t{pack}")
        iid += 1
        view += 1
