#!/usr/bin/env python3
"""HuffLabs leveling: tougher MVPs. Writes a db/import/mob_db.yml override for every
monster with MvpExp, scaling Hp and XP by the MVP's level tier.

Usage: gen_mvp.py --upstream DIR --out FILE   (DIR holds a copy of the server's db/re/mob_db.yml)

Tiers (spec): Level <100 -> HP x2, XP x1, 30 coins; 100-149 -> HP x5, XP x2, 60 coins;
150+ -> HP x10, XP x3.3, 100 coins. XP covers BaseExp, JobExp and MvpExp. Coins are paid
by content/coin-shop/server/coin_drops.txt using the same tiers.
"""
import argparse, os, re

HP_CAP = 2 ** 31 - 1


def tier(level):
    if level < 100:
        return (2, 1, 30)
    if level < 150:
        return (5, 2, 60)
    return (10, 3.3, 100)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--upstream', required=True)
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    with open(os.path.join(a.upstream, 'mob_db.yml')) as f:
        src = f.read()
    out = ["# HuffLabs leveling: tougher MVPs. Generated by content/leveling/gen_mvp.py, don't edit by hand.",
           'Header:', '  Type: MOB_DB', '  Version: 5', '', 'Body:']
    count = 0
    for b in re.split(r'\n  - Id: ', src.split('\nBody:', 1)[1])[1:]:
        f = dict(re.findall(r'\n    (\w+): (.*)', b))
        if 'MvpExp' not in f:
            continue
        iid = int(b.split('\n', 1)[0])
        hp_mult, xp_mult, _ = tier(int(f['Level']))
        out += ['  - Id: %d' % iid, '    AegisName: %s' % f['AegisName'], '    Name: %s' % f['Name'],
                '    Level: %s' % f['Level'], '    Hp: %d' % min(int(f['Hp']) * hp_mult, HP_CAP)]
        for k in ('BaseExp', 'JobExp', 'MvpExp'):
            if k in f:
                out.append('    %s: %d' % (k, round(int(f[k]) * xp_mult)))
        count += 1
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, 'w') as fh:
        fh.write('\n'.join(out) + '\n')
    print('%d MVPs written to %s' % (count, a.out))


if __name__ == '__main__':
    main()
