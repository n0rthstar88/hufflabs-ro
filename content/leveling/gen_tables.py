#!/usr/bin/env python3
"""HuffLabs leveling: writes rAthena import tables for base level 500 / job level 250
(final classes only) and stat points up to 500.

Usage: gen_tables.py --upstream DIR --out DIR
  DIR (upstream) holds copies of the server's db/re/{job_exp,statpoint,mob_db}.yml.
  Writes OUT/job_stats.yml (the XP tables; rAthena loads them as JOB_STATS) and OUT/statpoint.yml.

Curves:
  base: official through level 209, then one geometric curve so 275 -> 500 takes 40 h at 15x
  job:  official through job 29, then one geometric curve so 30 -> 250 takes 54 h at 15x
  XP/hour (1x) = median XP of the 20 highest-level non-boss monsters x 400 kills/h
  (1,200 kills/h shared by a party of 3).
"""
import argparse, os, re, statistics

FINAL_CLASSES = ("Dragon_Knight Meister Shadow_Cross Arch_Mage Cardinal Windhawk Imperial_Guard "
                 "Biolo Abyss_Chaser Elemental_Master Inquisitor Troubadour Trouvere Windhawk2 "
                 "Meister2 Dragon_Knight2 Imperial_Guard2 Sky_Emperor Soul_Ascetic Shinkiro "
                 "Shiranui Night_Watch Hyper_Novice Spirit_Handler Sky_Emperor2").split()
MAX_BASE, MAX_JOB = 500, 250
PACE = 15
KILLS_PER_HOUR_SHARE = 400
BASE_KEEP_THROUGH, BASE_WINDOW, BASE_HOURS = 210, (275, 500), 40
JOB_KEEP_THROUGH, JOB_WINDOW, JOB_HOURS = 30, (30, 250), 54
STAT_POINTS_PER_LEVEL = 387  # ceil(2.5 stats * 870 points (130 -> 1000) * cost 40 / 225 levels)


def _read(path):
    with open(path) as f:
        return f.read()


def _groups(text):
    body = text.split('\nBody:', 1)[1]
    return re.split(r'\n  - Jobs:', body)[1:]


def _jobs(group):
    return re.findall(r'\n      (\w+): true', '\n' + group.split('\n    ', 1)[0] + '\n' + group.split('\n    M', 1)[0])


def read_group_steps(path, maxkey, field, job):
    """Exp values (one per level, last one is rAthena's max-level filler) of the group
    for `job` that has `maxkey` and `field`."""
    for grp in _groups(_read(path)):
        if maxkey + ':' in grp and field + ':' in grp and job in _jobs(grp):
            seg = grp.split(field + ':', 1)[1]
            return [int(x) for x in re.findall(r'\n        Exp: (\d+)', seg)]
    raise KeyError((maxkey, field, job))


def soft_curve(official_steps, keep_through, max_level, target_xp, window):
    """Steps for levels 1..max_level-1. Official steps below `keep_through`, then
    x[L] = x[L-1] * r from level `keep_through`, with r chosen so the steps of levels
    window[0]..window[1]-1 add up to `target_xp`. Raises ValueError if no r in [1, 1.2] fits."""
    start = official_steps[keep_through - 2]
    n = max_level - keep_through

    def build(r):
        out, v = list(official_steps[:keep_through - 1]), float(start)
        for _ in range(n):
            v *= r
            out.append(int(v))
        return out

    def wsum(c):
        return sum(c[window[0] - 1:window[1] - 1])

    lo, hi = 1.0, 1.2
    if wsum(build(lo)) > target_xp or wsum(build(hi)) < target_xp:
        raise ValueError('target %d is out of reach for keep_through=%d' % (target_xp, keep_through))
    for _ in range(200):
        mid = (lo + hi) / 2
        if wsum(build(mid)) < target_xp:
            lo = mid
        else:
            hi = mid
    return build(hi)


def xp_per_hour_1x(mob_db_path):
    s = _read(mob_db_path)
    mobs = []
    for b in re.split(r'\n  - Id: ', s)[1:]:
        lv, be, je = (re.search(r'\n    %s: (\d+)' % k, b) for k in ('Level', 'BaseExp', 'JobExp'))
        if not lv or not be or re.search(r'\n    MvpExp:', b) or re.search(r'\n    Class: Boss', b):
            continue
        mobs.append((int(lv.group(1)), int(be.group(1)), int(je.group(1)) if je else 0))
    top = sorted(mobs, reverse=True)[:20]
    return (int(statistics.median(m[1] for m in top)) * KILLS_PER_HOUR_SHARE,
            int(statistics.median(m[2] for m in top)) * KILLS_PER_HOUR_SHARE)


def stat_points(official, to_level, per_level):
    """Cumulative stat points per level: official values, then +per_level per level."""
    out = list(official)
    while len(out) < to_level:
        out.append(out[-1] + per_level)
    return out


HEADER = ("# HuffLabs leveling: generated by content/leveling/gen_tables.py, don't edit by hand.\n"
          "Header:\n  Type: %s\n  Version: %d\n\nBody:\n")


def _exp_entry(maxkey, maxval, field, steps):
    filler = max(steps[-1] * 10, 10 ** 12)
    lines = ['  - Jobs:'] + ['      %s: true' % j for j in FINAL_CLASSES]
    lines += ['    %s: %d' % (maxkey, maxval), '    %s:' % field]
    for lvl, v in enumerate(list(steps) + [filler], 1):
        lines += ['      - Level: %d' % lvl, '        Exp: %d' % v]
    return '\n'.join(lines) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--upstream', required=True)
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    job_exp = os.path.join(a.upstream, 'job_exp.yml')
    base_rate, job_rate = xp_per_hour_1x(os.path.join(a.upstream, 'mob_db.yml'))

    base_off = read_group_steps(job_exp, 'MaxBaseLevel', 'BaseExp', FINAL_CLASSES[0])[:-1]
    job_off = read_group_steps(job_exp, 'MaxJobLevel', 'JobExp', FINAL_CLASSES[0])[:-1]
    base = soft_curve(base_off, BASE_KEEP_THROUGH, MAX_BASE, base_rate * PACE * BASE_HOURS, BASE_WINDOW)
    job = soft_curve(job_off, JOB_KEEP_THROUGH, MAX_JOB, job_rate * PACE * JOB_HOURS, JOB_WINDOW)

    os.makedirs(a.out, exist_ok=True)
    with open(os.path.join(a.out, 'job_stats.yml'), 'w') as f:
        f.write(HEADER % ('JOB_STATS', 4))
        f.write(_exp_entry('MaxBaseLevel', MAX_BASE, 'BaseExp', base))
        f.write(_exp_entry('MaxJobLevel', MAX_JOB, 'JobExp', job))

    sp = _read(os.path.join(a.upstream, 'statpoint.yml')).split('\nBody:', 1)[1]
    rows = re.findall(r'- Level: (\d+)\n    Points: (\d+)(?:\n    TraitPoints: (\d+))?', sp)
    official = [int(p) for _, p, _ in rows]
    traits = [int(t) if t else 0 for _, _, t in rows]
    pts = stat_points(official, MAX_BASE, STAT_POINTS_PER_LEVEL)
    traits += [traits[-1]] * (MAX_BASE - len(traits))
    with open(os.path.join(a.out, 'statpoint.yml'), 'w') as f:
        f.write(HEADER % ('STATPOINT_DB', 2))
        for lvl in range(1, MAX_BASE + 1):
            f.write('  - Level: %d\n    Points: %d\n' % (lvl, pts[lvl - 1]))
            if traits[lvl - 1]:
                f.write('    TraitPoints: %d\n' % traits[lvl - 1])

    h = lambda c, w, rate: sum(c[w[0] - 1:w[1] - 1]) / (rate * PACE)
    print('base 1x XP/h %d, job %d' % (base_rate, job_rate))
    print('15x hours: base 210->275 %.1f, 275->500 %.1f; job 30->250 %.1f' % (
        h(base, (210, 275), base_rate), h(base, BASE_WINDOW, base_rate), h(job, JOB_WINDOW, job_rate)))


if __name__ == '__main__':
    main()
